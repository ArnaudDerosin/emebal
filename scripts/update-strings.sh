#!/usr/bin/env bash
# Regenerates Resources/Localization/en.lproj/Localizable.strings from the
# code, then lists what each other language is missing or no longer needs.
#
# The Swift compiler finds every localizable string (SwiftUI text literals and
# String(localized:)), so run this after adding or changing interface text.
set -euo pipefail

cd "$(dirname "$0")/.."

# A fresh build each time: the compiler only lists the strings of the files it
# compiles, and an incremental build would skip unchanged ones.
OUT=".build/localized-strings"
rm -rf "$OUT" .build/strings
swift build --build-path .build/strings \
  -Xswiftc -emit-localized-strings \
  -Xswiftc -emit-localized-strings-path -Xswiftc "$OUT" >/dev/null

python3 - "$OUT" Resources/Localization <<'PYTHON'
import glob
import json
import os
import sys

out_dir, localization_dir = sys.argv[1], sys.argv[2]

# key -> (comment, files it appears in)
strings = {}
for path in sorted(glob.glob(os.path.join(out_dir, "*.stringsdata"))):
    data = json.load(open(path))
    source = os.path.basename(data.get("source", path))
    for entry in data.get("tables", {}).get("Localizable", []):
        comment, files = strings.setdefault(entry["key"], [entry.get("comment", ""), set()])
        if not comment and entry.get("comment"):
            strings[entry["key"]][0] = entry["comment"]
        files.add(source)

if not strings:
    sys.exit("No strings found: the build didn't produce any. Nothing was changed.")

def quote(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'

lines = [
    "/* English, generated by scripts/update-strings.sh from the code.",
    "   Don't edit by hand: change the text in the code and run the script again.",
    "   Other languages translate each value; the keys stay in English. */",
    "",
]
for key in sorted(strings, key=str.lower):
    comment, files = strings[key]
    note = ", ".join(sorted(files)) + (f": {comment}" if comment else "")
    lines += [f"/* {note} */", f"{quote(key)} = {quote(key)};", ""]

english = os.path.join(localization_dir, "en.lproj", "Localizable.strings")
os.makedirs(os.path.dirname(english), exist_ok=True)
open(english, "w").write("\n".join(lines))
print(f"en: {len(strings)} strings")

def keys_of(path):
    import subprocess
    plist = subprocess.run(["plutil", "-convert", "json", "-o", "-", path],
                           check=True, capture_output=True).stdout
    return set(json.loads(plist))

for path in sorted(glob.glob(os.path.join(localization_dir, "*.lproj", "Localizable.strings"))):
    language = os.path.basename(os.path.dirname(path)).removesuffix(".lproj")
    if language == "en":
        continue
    keys = keys_of(path)
    missing = sorted(set(strings) - keys)
    extra = sorted(keys - set(strings))
    status = "complete" if not missing and not extra else ""
    print(f"{language}: {len(keys)} strings {status}")
    for key in missing:
        print(f"  missing: {quote(key)}")
    for key in extra:
        print(f"  no longer used: {quote(key)}")
PYTHON
